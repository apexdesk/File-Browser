/// The `i`th glyph name.
pub(super) fn glyph_name(i: usize) -> Option<&'static str> {
    let (a, b) = (*GLYPH_ENDS.get(i)?, *GLYPH_ENDS.get(i + 1)?);
    GLYPH_NAMES.get(usize::from(a)..usize::from(b))
}

/// The character a glyph name stands for.
pub(super) fn glyph_char(name: &str) -> Option<u16> {
    let (mut lo, mut hi) = (0, GLYPH_CHARS.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        match glyph_name(mid)?.cmp(name) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => return GLYPH_CHARS.get(mid).copied(),
        }
    }
    None
}

/// The first glyph name of a character.
pub(super) fn char_glyph(c: u16) -> Option<&'static str> {
    glyph_name(GLYPH_CHARS.iter().position(|&u| u == c)?)
}

